package com.nextcloud.talk.utils

import okhttp3.HttpUrl
import okhttp3.Interceptor
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.Response
import okhttp3.ResponseBody.Companion.toResponseBody

data class UserAvatarAppearance(val dark: Boolean)

object UserAvatarPolicy {
    private val userPath = Regex("(?:^|/)avatar/[^/]+/[0-9]+(?:/dark)?$")
    private val proxyPath = Regex("/ocs/v[12]\\.php/apps/spreed/api/v[0-9]+/proxy/[^/]+/user-avatar/[0-9]+(?:/dark)?$")

    fun appliesTo(url: HttpUrl): Boolean =
        !url.encodedPath.contains("/remote.php/") &&
            (userPath.containsMatchIn(url.encodedPath) || proxyPath.containsMatchIn(url.encodedPath))

    fun cacheKey(key: String, dark: Boolean): String = "$key#talk-person-avatar-v2-${if (dark) "dark" else "light"}"
}

/** Replaces only avatars explicitly identified as generated by the server. */
class UserAvatarResponseInterceptor(private val fallbackImage: (Boolean) -> ByteArray) : Interceptor {
    override fun intercept(chain: Interceptor.Chain): Response {
        val request = chain.request()
        val response = chain.proceed(request)
        if (!UserAvatarPolicy.appliesTo(request.url) ||
            !response.isSuccessful ||
            response.header("X-NC-IsCustomAvatar")?.trim() != "0"
        ) {
            return response
        }
        val dark = request.tag(UserAvatarAppearance::class.java)?.dark ?: request.url.encodedPath.endsWith("/dark")
        val image = fallbackImage(dark)
        response.body.close()
        return response.newBuilder()
            .removeHeader("Content-Encoding")
            .header("Content-Type", "image/png")
            .header("Content-Length", image.size.toString())
            .body(image.toResponseBody("image/png".toMediaType()))
            .build()
    }
}
